# Exclude non-bowler wickets
valid_wickets = df[
    (df['wicket_player_out'].notna()) &
    (df['wicket_kind'] != 'run out')
]

top_bowlers = (
    valid_wickets.groupby('bowler')['wicket_player_out']
    .count()
    .sort_values(ascending=False)
    .head(5)
    .reset_index()
)

top_bowlers.columns = ['Bowler', 'Total Wickets']

print("\nTop 5 Bowlers by Wickets")
print(top_bowlers)